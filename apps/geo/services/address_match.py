"""Нормализация адресных строк для матча внешних источников к
``geo_addresses`` (ГАР, data.mos.ru и др.)."""

from __future__ import annotations


def norm(value: str) -> str:
    """Нормализация ключа матча: lowercase без пробелов и точек."""
    return value.lower().replace(" ", "").replace(".", "").strip()


# Типовые слова адресообразующих объектов: внешние источники сокращают
# («ул.»), OSM пишет полностью («улица») — схожесть считается по чистому
# имени.
TYPE_TOKENS = frozenset(
    {
        "ул", "улица", "пер", "переулок", "пр", "проспект", "прт", "пр-т",
        "пл", "площадь", "наб", "набережная", "бр", "б-р", "бульвар",
        "ш", "шоссе", "туп", "тупик", "аллея", "линия", "мкр",
        "микрорайон", "проезд", "прд", "пр-д", "квл", "кв-л", "квартал",
        "дор", "дорога", "тер", "территория", "км", "пос", "поселок",
        "посёлок", "снт", "рн", "р-н", "район", "г", "город", "д",
        "деревня", "с", "село", "х", "хутор", "ст", "станция", "парк",
        "канал", "просек", "тракт", "вал", "эст", "эстакада", "магистраль",
    }
)


def street_norm(value: str) -> str:
    """Чистое имя улицы: lowercase, без типовых слов и пунктуации."""
    cleaned = (
        value.lower()
        .replace("-", "")
        .replace(".", " ")
        .replace(",", " ")
    )
    tokens = [token for token in cleaned.split() if token not in TYPE_TOKENS]
    return " ".join(tokens)
