@lru_cache(maxsize=1)
def builtin_tool_ids() -> frozenset[str]:
    """Возвращает канонические id, зарезервированные для доверенных platform tools."""
    ids: list[str] = []
    for module_name, attr_name in BUILTIN_TOOL_SPECS:
        module = importlib.import_module(module_name)
        raw_tool = module.__dict__.get(attr_name)
        if raw_tool is None:
            raise TypeError(
                f"Builtin tool {module_name}.{attr_name} is missing"
            )
        named = cast(_NamedTool, raw_tool)
        tool_name = named.name
        if not tool_name.strip():
            raise TypeError(
                f"Builtin tool {module_name}.{attr_name} must expose non-empty str name"
            )
        ids.append(tool_name)
    return frozenset(ids)


def require_not_builtin_tool_id(tool_id: str, *, source: str) -> None:
    """SQL/MCP не владеют id platform builtin: иначе delete tuples снимает tool из picker."""
    if tool_id in builtin_tool_ids():
        raise ValueError(
            f"{source} must not use platform builtin tool_id {tool_id!r}"
        )


