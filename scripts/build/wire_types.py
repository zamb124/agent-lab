"""
Генерирует TypeScript wire-типы из OpenAPI `components.schemas` сервисов.

Для каждого сервиса:
1. Поднимает FastAPI app в отдельном процессе и читает `app.openapi()`
   (изоляция как в `scripts/docs/extract_openapi.py` — сервисы при импорте
   настраивают logging и хуки).
2. Эмитит `core/frontend/static/lib/events/wire/<svc>.gen.ts` —
   интерфейсы/алиасы моделей, которые UI получает по REST-зеркалу команд.

Файлы `.gen.ts` — сгенерированные, руками не правятся. Запуск:
`uv run python -m scripts.build.wire_types [--service rag]`.
"""
from __future__ import annotations

import argparse
import importlib
import inspect
import json
import logging
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = REPO_ROOT / "core" / "frontend" / "static" / "lib" / "events" / "wire"

# Сервисы с UI-потребителями wire-моделей: (имя, import_path приложения)
SERVICES: dict[str, str] = {
    "crm": "apps.crm.main:app",
    "flows": "apps.flows.main:app",
    "frontend": "apps.frontend.main:app",
    "geo": "apps.geo.main:app",
    "office": "apps.office.main:app",
    "rag": "apps.rag.main:app",
    "scheduler": "apps.scheduler.main:app",
    "search": "apps.search.main:app",
    "secrets": "apps.secrets.main:app",
    "shop": "apps.shop.main:app",
    "stock": "apps.stock.main:app",
    "sync": "apps.sync.main:app",
    "wiki": "apps.wiki.main:app",
    "worktracker": "apps.worktracker.main:app",
}

# Сервисы, чьи UI слушают события shared core-доменов (namespace вне `<svc>/`).
# Каталог живёт в `core/catalog`, владельца в `apps/` нет, а push-события
# `catalog/*` доходят до сокетов компании — UI stock и shop их типизируют.
EXTRA_EVENT_PREFIXES: dict[str, tuple[str, ...]] = {
    "shop": ("catalog/",),
    "stock": ("catalog/",),
}

_HEADER = """/**
 * AUTO-GENERATED by `uv run python -m scripts.build.wire_types` — не редактировать.
 *
 * Wire-модели сервиса `{svc}`: Pydantic-схемы OpenAPI → TS.
 */

"""


def _model_name(model: Any) -> str | None:
    """`__name__` модели или None для typing-конструкций без имени."""
    try:
        name = model.__name__
    except AttributeError:
        return None
    return name if isinstance(name, str) else None


def _unwrap_return(annotation: Any) -> Any:
    """Success-тип из return-аннотации op_*: убирает `| None` и Awaitable."""
    import types
    import typing

    if annotation is None or annotation is inspect.Signature.empty:
        return None
    origin = typing.get_origin(annotation)
    if origin in (typing.Union, types.UnionType):
        args = [a for a in typing.get_args(annotation) if a is not type(None)]
        return args[0] if len(args) == 1 else annotation
    if origin is not None and str(origin).endswith(("Awaitable", "Coroutine")):
        args = typing.get_args(annotation)
        return _unwrap_return(args[-1]) if args else None
    return annotation


def _iter_wire_models(
    service: str,
) -> tuple[list[Any], list[tuple[str, Any, Any]], list[tuple[str, Any]]]:
    """Wire-модели сервиса: (модели, команды, события).

    Команды — `<SVC>_OPERATIONS` (payload_model + return fn): декларативный
    каталог, источник правды и для REST-зеркала.
    События — `register_platform_event(type, PayloadModel)` из
    `apps.<svc>.events`: payload-модель живёт в реестре `core.events.registry`.
    """
    import typing

    module = importlib.import_module(f"apps.{service}.realtime.command_router")
    catalog = next(
        (v for name, v in vars(module).items() if name.endswith("_OPERATIONS") and isinstance(v, dict)),
        None,
    )
    if catalog is None:
        raise RuntimeError(f"{service}: *_OPERATIONS каталог не найден в command_router")
    models: list[Any] = []
    commands: list[tuple[str, Any, Any]] = []
    for command_type, op in catalog.items():
        payload_model = op.payload_model
        if payload_model is not None:
            models.append(payload_model)
        fn = op.fn
        ret = None
        if fn is not None:
            try:
                ret = typing.get_type_hints(fn).get("return")
            except Exception:  # noqa: BLE001 — неразрешимые ForwardRef пропускаем
                ret = fn.__annotations__.get("return")
            ret = _unwrap_return(ret)
            if ret is not None:
                models.append(ret)
        commands.append((command_type, payload_model, ret))

    events: list[tuple[str, Any]] = []
    try:
        importlib.import_module(f"apps.{service}.events")
    except ModuleNotFoundError:
        pass
    from core.events.registry import (  # noqa: PLC0415 — после поднятия сервиса
        platform_event_payload_model,
        registered_platform_event_types,
    )

    extra_prefixes = EXTRA_EVENT_PREFIXES.get(service, ())
    for event_type in registered_platform_event_types():
        if not event_type.startswith((f"{service}/", *extra_prefixes)):
            continue
        payload_model = platform_event_payload_model(event_type)
        models.append(payload_model)
        events.append((event_type, payload_model))
    return models, commands, events


def _schema_json(
    service: str, app_path: str
) -> tuple[dict[str, Any], list[tuple[str, str, str]], list[tuple[str, str]]]:
    """Собирает JSON-схемы wire-моделей сервиса через TypeAdapter по-модельно.

    `app.openapi()` не используется: REST-зеркала декларируют `dict`, а один
    не-генерируемый тип (protobuf, IsInstance) ронял бы весь дамп.
    """
    module_path, object_name = app_path.split(":")
    importlib.import_module(module_path)  # поднимает сервис и его модели
    from pydantic import TypeAdapter

    models, commands, events = _iter_wire_models(service)
    schemas: dict[str, Any] = {}
    skipped: list[str] = []
    for model in models:
        try:
            schema = TypeAdapter(model).json_schema(
                ref_template="#/components/schemas/{model}"
            )
        except Exception as exc:  # noqa: BLE001 — пропускаем не-генерируемые типы
            skipped.append(f"{model!r}: {exc.__class__.__name__}")
            continue
        nested = schema.pop("$defs", {})
        schemas.update(nested)
        name = _model_name(model)
        if name is not None and ("type" in schema or "properties" in schema or "$ref" in schema):
            schemas.setdefault(name, schema)
        title = schema.get("title")
        if name is None and isinstance(title, str):
            schemas.setdefault(title, schema)
    if skipped:
        logger.warning("wire: %s — пропущено %d не-генерируемых моделей: %s", service, len(skipped), "; ".join(skipped[:5]))
    if not schemas:
        raise RuntimeError(f"{service}: wire-схемы не собраны")

    emitted = {_safe_ident(k) for k in schemas if isinstance(schemas[k], dict)}

    def _model_ident(model: Any) -> str:
        name = _model_name(model)
        if name is None:
            return "unknown"
        ident = _safe_ident(name)
        return ident if ident in emitted else "unknown"

    command_entries: list[tuple[str, str, str]] = []
    for command_type, payload_model, ret in commands:
        payload_name = (
            _model_ident(payload_model)
            if payload_model is not None
            else "Record<string, never>"
        )
        result_name = "null"
        if ret is not None:
            try:
                ret_schema = TypeAdapter(ret).json_schema(
                    ref_template="#/components/schemas/{model}"
                )
            except Exception:  # noqa: BLE001 — модель без схемы → unknown
                result_name = "unknown"
            else:
                ref = ret_schema.get("$ref")
                if isinstance(ref, str):
                    result_name = _ref_name(ref)
                elif isinstance(ret_schema.get("title"), str):
                    result_name = _safe_ident(ret_schema["title"])
                else:
                    result_name = _ts_type(ret_schema, set())
                if re.fullmatch(r"[A-Za-z_]\w*", result_name) and result_name not in emitted:
                    result_name = "unknown"
        command_entries.append((command_type, payload_name, result_name))

    event_entries = [
        (event_type, _model_ident(payload_model))
        for event_type, payload_model in events
    ]
    return schemas, command_entries, event_entries


def _ref_name(ref: str) -> str:
    name = ref.rsplit("/", 1)[-1]
    return _safe_ident(name)


def _safe_ident(name: str) -> str:
    ident = "".join(ch if ch.isalnum() or ch == "_" else "_" for ch in name)
    if ident and ident[0].isdigit():
        ident = f"_{ident}"
    if not ident:
        raise RuntimeError("пустое имя схемы")
    return ident


def _literal(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def _doc(description: str | None, title: str | None, indent: str) -> str:
    text = description or title
    if not text:
        return ""
    lines = [indent + "/**"]
    for line in str(text).splitlines():
        lines.append(f"{indent} * {line.rstrip()}")
    lines.append(indent + " */")
    return "\n".join(lines) + "\n"


def _ts_type(schema: dict[str, Any] | bool | None, seen: set[str]) -> str:
    if schema is True or schema is None or schema == {}:
        return "unknown"
    if schema is False:
        return "never"
    if "$ref" in schema:
        return _ref_name(schema["$ref"])
    if "anyOf" in schema or "oneOf" in schema:
        parts = schema.get("anyOf") or schema.get("oneOf") or []
        types = [_ts_type(s, seen) for s in parts]
        return " | ".join(dict.fromkeys(types)) or "unknown"
    if "allOf" in schema:
        parts = [_ts_type(s, seen) for s in schema["allOf"]]
        return " & ".join(parts) or "unknown"
    if "enum" in schema:
        return " | ".join(_literal(v) for v in schema["enum"])
    if "const" in schema:
        return _literal(schema["const"])

    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(_ts_type({**schema, "type": one}, seen) for one in t)
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array" or "items" in schema or "prefixItems" in schema:
        if "prefixItems" in schema:
            items = ", ".join(_ts_type(s, seen) for s in schema["prefixItems"])
            return f"[{items}]"
        inner = _ts_type(schema.get("items"), seen)
        return f"({inner})[]" if ("|" in inner or "&" in inner) else f"{inner}[]"
    if t == "object" or "properties" in schema or "additionalProperties" in schema:
        props = schema.get("properties") or {}
        required = set(schema.get("required") or [])
        addl = schema.get("additionalProperties")
        if not props and isinstance(addl, dict):
            return f"Record<string, {_ts_type(addl, seen)}>"
        members = []
        for prop_name, prop_schema in props.items():
            opt = "" if prop_name in required else "?"
            prop_doc = _doc(prop_schema.get("description") if isinstance(prop_schema, dict) else None, None, "    ")
            prop_type = _ts_type(prop_schema, seen)
            if opt and "undefined" not in prop_type:
                prop_type = f"{prop_type} | undefined"
            members.append(f"{prop_doc}    {json.dumps(prop_name, ensure_ascii=False)}{opt}: {prop_type};")
        if isinstance(addl, dict):
            members.append(f"    [key: string]: {_ts_type(addl, seen)};")
        else:
            # Wire-объект может нести ключи вне схемы; индекс-сигнатура
            # удовлетворяет `ResourceItem` и описывает JSON честно.
            members.append("    [key: string]: unknown;")
        body = "\n".join(members)
        return "{\n" + body + "\n}" if members else "Record<string, unknown>"
    return "unknown"


def emit_ts(
    service: str,
    schemas: dict[str, Any],
    commands: list[tuple[str, str, str]],
    events: list[tuple[str, str]],
) -> str:
    chunks = [_HEADER.format(svc=service)]
    for name in sorted(schemas):
        schema = schemas[name]
        if not isinstance(schema, dict):
            continue
        ident = _safe_ident(name)
        doc = _doc(schema.get("description"), schema.get("title"), "")
        is_object = bool(schema.get("properties")) and "enum" not in schema and "$ref" not in schema
        keyword = "interface" if is_object else "type"
        body = _ts_type(schema, set())
        if keyword == "interface":
            chunks.append(f"{doc}export interface {ident} {body}\n")
        else:
            chunks.append(f"{doc}export type {ident} = {body};\n")

    map_ident = _map_ident(service, "Command")
    entries = ",\n".join(
        f'    "{command_type}": {{ payload: {payload}; result: {result} }}'
        for command_type, payload, result in sorted(commands)
    )
    chunks.append(
        "/**\n"
        " * Карта команд сервиса: `type` → `{ payload, result }`.\n"
        " * Типизированный dispatch/оп-результат по имени команды.\n"
        " */\n"
        f"export interface {map_ident} {{\n{entries}\n}}\n"
    )

    event_map_ident = _map_ident(service, "Event")
    event_entries = ",\n".join(
        f'    "{event_type}": {payload}' for event_type, payload in sorted(events)
    )
    chunks.append(
        "/**\n"
        " * Карта push-событий сервиса (`register_platform_event`): `type` → payload.\n"
        " */\n"
        f"export interface {event_map_ident} {{\n{event_entries}\n}}\n"
    )
    return "\n".join(chunks)


def _map_ident(service: str, kind: str) -> str:
    return f"{service.title().replace('_', '')}{kind}Map"


def emit_index_ts(services: list[str]) -> str:
    """Объединённая карта команд и событий всех сервисов.

    `PlatformCommandMap` — единая точка инференса результатов по `commandType`;
    `PlatformEventMap` — payload push-событий по типу.
    """
    imports: list[str] = []
    command_names: list[str] = []
    event_names: list[str] = []
    for service in services:
        command_names.append(_map_ident(service, "Command"))
        event_names.append(_map_ident(service, "Event"))
        imports.append(
            f"import type {{ {command_names[-1]}, {event_names[-1]} }} from './{service}.gen.js';"
        )
    return (
        _HEADER.format(svc="platform")
        + "\n".join(imports)
        + "\n\nexport interface PlatformCommandMap extends\n    "
        + ",\n    ".join(command_names)
        + " {}\n\nexport interface PlatformEventMap extends\n    "
        + ",\n    ".join(event_names)
        + " {}\n"
    )


def _run_dump(
    service: str,
) -> tuple[dict[str, Any], list[tuple[str, str, str]], list[tuple[str, str]]]:
    script = Path(__file__).resolve()
    with tempfile.NamedTemporaryFile(suffix=".json", delete=False) as tmp:
        tmp_path = Path(tmp.name)
    try:
        subprocess.run(
            [sys.executable, str(script), "--dump", service, "--output", str(tmp_path)],
            check=True,
            cwd=REPO_ROOT,
        )
        return json.loads(tmp_path.read_text(encoding="utf-8"))
    finally:
        tmp_path.unlink(missing_ok=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dump", help="internal: dump schemas for service")
    parser.add_argument("--output", help="internal: dump output path")
    parser.add_argument("--service", action="append", help="генерировать только указанные сервисы")
    args = parser.parse_args()

    if args.dump:
        Path(args.output).write_text(
            json.dumps(_schema_json(args.dump, SERVICES[args.dump])),
            encoding="utf-8",
        )
        return

    services = args.service or list(SERVICES)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for service in services:
        if service not in SERVICES:
            raise SystemExit(f"неизвестный сервис: {service}")
        schemas, commands, events = _run_dump(service)
        out_file = OUT_DIR / f"{service}.gen.ts"
        out_file.write_text(emit_ts(service, schemas, commands, events), encoding="utf-8")
        logger.info(
            "wire: %s → %s (%d схем, %d команд, %d событий)",
            service, out_file.relative_to(REPO_ROOT), len(schemas), len(commands), len(events),
        )
    index_file = OUT_DIR / "index.ts"
    index_file.write_text(emit_index_ts(list(SERVICES)), encoding="utf-8")
    logger.info("wire: → %s", index_file.relative_to(REPO_ROOT))


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
    main()
